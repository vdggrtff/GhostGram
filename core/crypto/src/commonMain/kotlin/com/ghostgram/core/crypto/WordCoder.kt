    // Обратный индекс для быстрого декодирования (Слово -> Байт)
    private val REVERSE_DICTIONARY: Map<String, Byte> = DICTIONARY.withIndex().associate { (index, word) ->
        word to index.toByte()
    }

    /**
     * Превращает ByteArray в строку со словами.
     * Добавляет префикс 👻, чтобы мессенджер понимал, что это крипто-пакет.
     */
    fun encode(bytes: ByteArray): String {
        val words = bytes.map { byte ->
            val unsignedInt = byte.toInt() and 0xFF // Превращаем Byte (-128..127) в Int (0..255)
            DICTIONARY[unsignedInt] // Если словарь правильного размера, тут никогда не будет краша
        }
        return "👻 " + words.joinToString(" ")
    }

    /**
     * Превращает строку со словами обратно в ByteArray
     */
    fun decode(text: String): ByteArray? {
        if (!text.startsWith("👻 ")) return null

        val words = text.removePrefix("👻 ").split(" ").filter { it.isNotBlank() }
        val bytes = ByteArray(words.size)

        for (i in words.indices) {
            val byte = REVERSE_DICTIONARY[words[i]] ?: return null // Если слово не из словаря - пакет поврежден
            bytes[i] = byte
        }

        return bytes
    }
